/**
 * INTERNAL / READ-ONLY: compare a separately fetched Razorpay evidence snapshot
 * against Milvanta's historical signed-webhook observations and local refund
 * requests. Does NOT fetch Razorpay, authenticate the supplied snapshot, or
 * authorize any payout, credit, entitlement extension or physical delivery.
 *
 * The caller must independently establish account, source authenticity,
 * completeness, and time before relying on the report. No UI/cron routes.
 */
import { acquireClient } from './subscriptionService.js';

function safeInt(value, field, {positive=false}={}) {
  const n = typeof value==='number' ? value :
    typeof value==='string' && /^[0-9]+$/.test(value) ? Number(value) : NaN;
  if(!Number.isSafeInteger(n) || n<0 || (positive&&n===0)) {
    throw Error('invalid_gateway_snapshot_'+field);
  }
  return n;
}
function id(str,prefix) {
  return typeof str==='string' && str.startsWith(prefix) &&
    /^[A-Za-z0-9_]+$/.test(str) && str.length>prefix.length;
}
function sumSafe(values, field) {
  return values.reduce((s,n)=>{
    const next=s+n;
    if(!Number.isSafeInteger(next)) throw Error('gateway_snapshot_'+field+'_overflow');
    return next;
  },0);
}
function unique(items){return [...new Set(items)];}
const blank=()=>({
  status:'manual_reconciliation_required',
  source:'supplied_razorpay_snapshot_not_independently_authenticated_by_this_module',
  snapshotComplete:false,
  capturedPaymentCount:0,
  observedCapturedAmountPaise:0,
  processedRefundAmountPaise:0,
  outstandingGatewayRefundAmountPaise:0,
  gatewayCycles:[],
  paymentComparisons:[],
  refundComparisons:[],
  reviewFlags:[],
  customerPayableCreditPaise:null,
  customerRefundableAmountPaise:null,
  mayAutoApplyCredits:false,
  mayAutoRefund:false,
  mayAutoGenerateDeliveries:false,
  independentlyConfirmedSettlement:false
});

/**
 * Raw payment, invoice and refund fields intentionally follow Razorpay's
 * read-only API entity shape, rather than equating local plan totals to cash.
 */
export function assessRecurringGatewaySnapshot({
  subscription, captureObservations=[], localRefundRequests=[], gatewaySnapshot
}={}) {
  if(!subscription?.id || !id(subscription.razorpay_subscription_id,'sub_')) {
    throw Error('gateway_snapshot_subscription_required');
  }
  const report=blank(),flags=[];
  if(!gatewaySnapshot || typeof gatewaySnapshot!=='object') {
    report.reviewFlags=['independent_gateway_snapshot_missing'];
    return report;
  }
  const snapshot=gatewaySnapshot;
  const payments=Array.isArray(snapshot.payments)?snapshot.payments:[];
  const refunds=Array.isArray(snapshot.refunds)?snapshot.refunds:[];
  const invoices=Array.isArray(snapshot.invoices)?snapshot.invoices:[];
  report.snapshotComplete=snapshot.complete===true;
  if(snapshot.complete!==true) flags.push('gateway_snapshot_partial_or_unknown');
  if(snapshot.accountMode!=='live') flags.push('gateway_snapshot_not_explicitly_live');
  if(snapshot.subscriptionId!==subscription.razorpay_subscription_id) flags.push('gateway_snapshot_foreign_subscription');
  if(typeof snapshot.retrievedAt!=='string' ||
     !Number.isFinite(Date.parse(snapshot.retrievedAt))) {
    flags.push('gateway_snapshot_retrieval_time_unverified');
  }
  if(payments.length===0) flags.push('gateway_snapshot_no_payments');
  const observationById=new Map();
  for(const o of captureObservations) {
    if(!id(o.gateway_payment_id,'pay_')) {
      flags.push('malformed_webhook_capture_observation');
      continue;
    }
    if(observationById.has(o.gateway_payment_id)) {
      flags.push('duplicate_local_payment_observation');
      continue;
    }
    observationById.set(o.gateway_payment_id,o);
  }
  const invoicesById=new Map(),invoicePaymentAssignments=new Map();
  for(const invoice of invoices) {
    if(!id(invoice.id,'inv_') || invoicesById.has(invoice.id)) {
      flags.push('gateway_duplicate_or_invalid_invoice');
      continue;
    }
    invoicesById.set(invoice.id,invoice);
    if(invoice.subscription_id!==subscription.razorpay_subscription_id ||
       invoice.status!=='paid' ||
       !Number.isSafeInteger(invoice.billing_start) ||
       !Number.isSafeInteger(invoice.billing_end) ||
       invoice.billing_start<1 || invoice.billing_end<=invoice.billing_start) {
      flags.push('invoice_subscription_status_or_cycle_unverified');
    }
    if(invoice.payment_id) {
      if(!id(invoice.payment_id,'pay_')) flags.push('invoice_invalid_payment_id');
      if(invoicePaymentAssignments.has(invoice.payment_id)) {
        flags.push('same_payment_assigned_multiple_invoices');
      }
      invoicePaymentAssignments.set(invoice.payment_id,invoice.id);
    }
  }

  const paymentsById=new Map(),capturedAmounts=[],cycleMap=new Map();
  for(const p of payments) {
    if(!id(p.id,'pay_') || paymentsById.has(p.id)) {
      flags.push('gateway_duplicate_or_invalid_payment_id');
      continue;
    }
    paymentsById.set(p.id,p);
    const amount=safeInt(p.amount,'payment_amount',{positive:true});
    const refunded=p.amount_refunded===undefined || p.amount_refunded===null
      ? null:safeInt(p.amount_refunded,'amount_refunded');
    const captured=(p.captured===true &&
       (p.status==='captured'||p.status==='refunded') &&
       p.currency==='INR');
    if(!captured) flags.push('gateway_payment_not_confirmed_captured_inr');
    if(refunded===null) flags.push('gateway_payment_refund_total_missing');
    if(refunded!==null && refunded>amount) flags.push('gateway_payment_refunded_exceeds_capture');
    if(p.subscription_id!=null &&
       p.subscription_id!==subscription.razorpay_subscription_id) {
      flags.push('gateway_payment_foreign_subscription');
    }
    const invoiceId=p.invoice_id||invoicePaymentAssignments.get(p.id)||null;
    const invoice=invoiceId?invoicesById.get(invoiceId):null;
    if(!invoice) flags.push('gateway_payment_cycle_invoice_missing');
    else {
      if(invoice.payment_id && invoice.payment_id!==p.id) flags.push('invoice_payment_conflict');
      if(p.invoice_id && p.invoice_id!==invoice.id) flags.push('invoice_payment_conflict');
      if(invoice.subscription_id!==subscription.razorpay_subscription_id ||
         invoice.status!=='paid' ||
         !Number.isSafeInteger(invoice.billing_start) ||
         !Number.isSafeInteger(invoice.billing_end) ||
         invoice.billing_end<=invoice.billing_start) {
        flags.push('gateway_payment_cycle_unverified');
      } else {
        const k=invoice.billing_start+':'+invoice.billing_end;
        const cycle=cycleMap.get(k)||{
          billingStart:invoice.billing_start,billingEnd:invoice.billing_end,
          paymentIds:[],capturedAmountPaise:0,invoiceIds:[]
        };
        cycle.paymentIds.push(p.id);
        cycle.invoiceIds.push(invoice.id);
        if(captured) cycle.capturedAmountPaise=sumSafe([cycle.capturedAmountPaise,amount],'cycle_total');
        cycleMap.set(k,cycle);
      }
    }
    const obs=observationById.get(p.id);
    if(!obs) flags.push('gateway_payment_absent_from_signed_webhook_observations');
    else if(obs.gateway_subscription_id!==subscription.razorpay_subscription_id ||
      safeInt(obs.amount_paise,'observed_amount')!==amount ||
      obs.proof_level!=='signed_webhook_payment_entity') {
      flags.push('gateway_and_webhook_observation_mismatch');
    }
    if(captured)capturedAmounts.push(amount);
    report.paymentComparisons.push({
      paymentId:p.id,invoiceId,captured,currency:p.currency,
      amountPaise:amount,reportedRefundedPaise:refunded,
      observedWebhook:!!obs,
      consistentWithWebhook:!!obs &&
        obs.gateway_subscription_id===subscription.razorpay_subscription_id &&
        Number(obs.amount_paise)===amount,
      // Payment status alone does not prove its funds were settled to bank.
      independentlyConfirmedSettlement:false
    });
  }

  for(const [pid] of observationById){
    if(!paymentsById.has(pid))flags.push('webhook_capture_absent_from_gateway_snapshot');
  }
  for(const cycle of cycleMap.values()){
    if(cycle.paymentIds.length!==1) flags.push('multiple_payments_per_gateway_invoice_cycle');
  }
  const cycles=[...cycleMap.values()].sort((a,b)=>a.billingStart-b.billingStart);
  for(let i=1;i<cycles.length;i++){
    if(cycles[i].billingStart<cycles[i-1].billingEnd){
      flags.push('overlapping_gateway_invoice_cycles');
    }
  }
  report.gatewayCycles=cycles;
  report.capturedPaymentCount=capturedAmounts.length;
  report.observedCapturedAmountPaise=sumSafe(capturedAmounts,'captured_total');

  const refundsById=new Map(),processedTotals=new Map(),pendingTotals=[];
  for(const refund of refunds){
    if(!id(refund.id,'rfnd_') || refundsById.has(refund.id)){
      flags.push('gateway_duplicate_or_invalid_refund_id');
      continue;
    }
    refundsById.set(refund.id,refund);
    const amount=safeInt(refund.amount,'refund_amount',{positive:true});
    if(refund.currency!=='INR' || !id(refund.payment_id,'pay_') ||
       !paymentsById.has(refund.payment_id)){
      flags.push('gateway_refund_currency_or_payment_mismatch');
    }
    if(refund.status==='processed'){
      processedTotals.set(refund.payment_id,
        sumSafe([processedTotals.get(refund.payment_id)||0,amount],'processed_refunds'));
    }else if(['pending','created','queued','processing'].includes(refund.status)){
      pendingTotals.push(amount);
      flags.push('gateway_refund_not_final');
    }else if(!['failed','reversed'].includes(refund.status)){
      flags.push('gateway_unknown_refund_status');
    }
    report.refundComparisons.push({
      refundId:refund.id,paymentId:refund.payment_id,status:refund.status,
      amountPaise:amount,terminalProcessed:refund.status==='processed'
    });
  }
  report.processedRefundAmountPaise=sumSafe([...processedTotals.values()],'total_processed_refunds');
  report.outstandingGatewayRefundAmountPaise=sumSafe(pendingTotals,'total_outstanding_refunds');
  for(const p of paymentsById.values()){
    const processed=processedTotals.get(p.id)||0;
    if(processed>safeInt(p.amount,'refund_check_payment_amount',{positive:true})){
      flags.push('processed_refund_exceeds_payment_capture');
    }
    if(p.amount_refunded===null || p.amount_refunded===undefined){
      flags.push('payment_refunded_total_unknown');
    }else if(processed!==safeInt(p.amount_refunded,'refund_check_refunded_amount')){
      flags.push('refund_totals_do_not_match_gateway_payment');
    }
  }
  for(const req of localRefundRequests){
    if(req.status==='rejected'||req.status==='failed')continue;
    if(req.status==='pending'||req.status==='processing'){
      flags.push('local_refund_not_final');
      continue;
    }
    if(req.status==='approved'){
      flags.push('local_approved_refund_not_proof_of_gateway_settlement');
      continue;
    }
    if(req.status==='processed'){
      if(!id(req.gateway_refund_id,'rfnd_') ||
         !refundsById.has(req.gateway_refund_id)){
        flags.push('local_processed_refund_missing_from_gateway_snapshot');
      }else{
        const ref=refundsById.get(req.gateway_refund_id);
        if(ref.status!=='processed'||ref.payment_id!==req.payment_id ||
           safeInt(ref.amount,'local_match_gateway_amount')!==safeInt(req.approved_amount_paise,'local_approved_amount',{positive:true})){
          flags.push('local_processed_refund_receipt_mismatch');
        }
      }
    }else{
      flags.push('local_unknown_refund_status');
    }
  }
  const localProcessedIds=new Set(localRefundRequests
    .filter(x=>x.status==='processed' && id(x.gateway_refund_id,'rfnd_'))
    .map(x=>x.gateway_refund_id));
  for(const ref of refunds){
    if(ref.status==='processed' && !localProcessedIds.has(ref.id)){
      flags.push('gateway_processed_refund_absent_from_local_records');
    }
  }
  report.reviewFlags=unique(flags);
  // No monetary compensation can ever be concluded from this module, even
  // when every supplied record matches. A snapshot is not bank settlement.
  return report;
}


/**
 * Internal-only database-backed comparison with separately supplied gateway
 * evidence. A transaction snapshots Milvanta tables READ ONLY; no network,
 * Razorpay credentials, webhook modifications, customer changes or dispatch.
 * The supplied snapshot's provenance is not authenticated here.
 */
export async function previewRecurringGatewaySnapshotReconciliation(pool,{
  subscriptionId,gatewaySnapshot
}={}) {
  const idNum=Number(subscriptionId);
  if(!Number.isSafeInteger(idNum)||idNum<=0){
    return {success:false,reason:'invalid_subscription_id'};
  }
  const {client,release}=await acquireClient(pool);
  try {
    await client.query('BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY');
    const subs=await client.query(
      'SELECT id,customer_id,razorpay_subscription_id,plan_type,notes FROM customer_subscriptions WHERE id=$1',
      [idNum]);
    const sub=subs.rows[0];
    if(!sub){
      await client.query('COMMIT');
      return {success:false,reason:'subscription_not_found'};
    }
    const obs=await client.query(
      'SELECT gateway_payment_id,gateway_subscription_id,amount_paise,currency,'+
      'paid_count_at_event,proof_level FROM recurring_subscription_capture_observations '+
      'WHERE subscription_id=$1 ORDER BY id',
      [idNum]
    );
    const refunds=await client.query(
      'SELECT status,approved_amount_paise,gateway_refund_id,payment_id '+
      'FROM refund_requests WHERE subscription_id=$1 ORDER BY id',
      [idNum]
    );
    const report=assessRecurringGatewaySnapshot({
      subscription:sub,captureObservations:obs.rows,
      localRefundRequests:refunds.rows,gatewaySnapshot
    });
    await client.query('COMMIT');
    return {success:true,...report};
  }catch(err){
    await client.query('ROLLBACK').catch(()=>{});
    throw err;
  }finally{release();}
}
