/**
 * Date-by-date finance decision worksheet. READ-ONLY, INTERNAL.
 *
 * The first-cycle owed-morning ledger counts mornings rather than assigning
 * legally compensable dates, so this deliberately NEVER matches an owed morning
 * to a skip date, pays a refund, credits a renewal or generates deliveries.
 * Gateway snapshots must be independently retrieved/authenticated by finance.
 */
import { acquireClient, getEffectivePaidThroughDate } from './subscriptionService.js';
import { assessRecurringGatewaySnapshot } from './recurringGatewaySnapshotReconciliation.js';

const unique = values => [...new Set(values)];
const safeInt = value => {
  const n = (typeof value === 'number' || (typeof value === 'string' && /^-?\d+$/.test(value)))
    ? Number(value) : NaN;
  if (!Number.isSafeInteger(n)) throw new Error('invalid_finance_review_integer');
  return n;
};
const positiveId = value => safeInt(value) > 0;
function validDay(day) {
  if (typeof day !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(day)) return false;
  const [y,m,d] = day.split('-').map(Number);
  const date = new Date(Date.UTC(y,m-1,d));
  return date.getUTCFullYear() === y &&
    date.getUTCMonth() === m-1 && date.getUTCDate() === d;
}
function initDate(date) {
  return {
    deliveryDate:date,positiveSourceRows:0,reversalSourceRows:0,
    signedClaimDays:0,signedClaimPaise:0,
    creditAdjustmentIds:[],sourceKinds:[],deliveryStatuses:[],
    reservedPrototypeCount:0,flags:[]
  };
}
function noActions() {
  return {
    customerPayableCreditPaise:null,
    customerRefundableAmountPaise:null,
    newDeliveryEntitlementDays:null,
    mayAutoApplyCredits:false,mayAutoRefund:false,mayAutoGenerateDeliveries:false,
    independentlyConfirmedSettlement:false
  };
}
function sumChecked(a,b) {
  const result=a+b;
  if (!Number.isSafeInteger(result)) throw new Error('finance_review_integer_overflow');
  return result;
}

/**
 * All input arrays are from one local read-only snapshot. This pure function
 * groups, checks, and labels evidence; it does not choose a compensation policy.
 */
export function buildRecurringFinanceDecisionWorksheet({
  subscription,paidThroughDate=null,adjustments=[],creditSources=[],
  deliveryOrders=[],obligations=[],reservations=[],refundRequests=[],
  captureObservations=[],gatewaySnapshot=null
}={}) {
  if(!subscription || !positiveId(subscription.id) || !positiveId(subscription.customer_id)) {
    throw new Error('finance_review_subscription_required');
  }
  const dailyRate=safeInt(subscription.cost_per_day_paise);
  if(dailyRate<=0)throw new Error('finance_review_daily_rate_invalid');
  const globalFlags=[];
  if(subscription.notes?.keyMode!=='live') globalFlags.push('gateway_mode_not_verified_live');
  if(subscription.notes?.fulfillmentEntitled!==true) globalFlags.push('entitlement_not_verified');
  if(!validDay(paidThroughDate)) globalFlags.push('paid_through_unverified');
  if(Number(subscription.notes?.months)!==1) globalFlags.push('multimonth_policy_not_approved');
  if(Number(subscription.notes?.paidCount)!==1) globalFlags.push('renewal_cycle_requires_review');
  if(!gatewaySnapshot)globalFlags.push('independent_gateway_snapshot_missing');

  const adjustmentMap=new Map();
  for(const a of adjustments) {
    const id=safeInt(a.id),days=safeInt(a.days_count),amount=safeInt(a.amount_paise);
    if(id<=0||adjustmentMap.has(id))throw new Error('invalid_or_duplicate_finance_adjustment_id');
    adjustmentMap.set(id,{id,type:a.adjustment_type,expectedDays:days,
      expectedPaise:amount,provenanceDays:0,provenancePaise:0,provenanceRows:0});
  }
  const dates=new Map();
  for(const source of creditSources){
    const id=safeInt(source.billing_adjustment_id);
    const adjustment=adjustmentMap.get(id);
    if(!adjustment) {
      globalFlags.push('orphan_date_source');
      continue;
    }
    const day=source.delivery_date;
    if(!validDay(day)) {
      globalFlags.push('date_source_invalid_day');
      continue;
    }
    const delta=safeInt(source.days_delta), amount=safeInt(source.amount_paise);
    const dayInfo=dates.get(day)||initDate(day);
    if(![-1,1].includes(delta) || amount!==dailyRate*delta){
      dayInfo.flags.push('date_source_inconsistent_amount_or_sign');
    }
    if(source.evidence_state!=='date_known_payment_unverified') {
      dayInfo.flags.push('date_source_unrecognized_evidence_state');
    }
    if(!['skip','unskip','vacation','pause_resume'].includes(source.source_kind)){
      dayInfo.flags.push('date_source_unknown_kind');
    }
    if(delta>0)dayInfo.positiveSourceRows++;
    if(delta<0)dayInfo.reversalSourceRows++;
    dayInfo.signedClaimDays=sumChecked(dayInfo.signedClaimDays,delta);
    dayInfo.signedClaimPaise=sumChecked(dayInfo.signedClaimPaise,amount);
    dayInfo.creditAdjustmentIds.push(id);
    dayInfo.sourceKinds.push(source.source_kind);
    adjustment.provenanceDays=sumChecked(adjustment.provenanceDays,delta);
    adjustment.provenancePaise=sumChecked(adjustment.provenancePaise,amount);
    adjustment.provenanceRows++;
    if(!source.payment_id || !source.billing_cycle_reference) {
      dayInfo.flags.push('date_credit_payment_cycle_unverified');
    }
    dates.set(day,dayInfo);
  }

  for(const order of deliveryOrders) {
    const day=order.delivery_date;
    if(!validDay(day)) {globalFlags.push('delivery_order_invalid_day');continue;}
    const rec=dates.get(day)||initDate(day);
    const source=order.fulfillment_source;
    if(!['paid_entitlement','owed_morning_prototype'].includes(source)) {
      rec.flags.push('unknown_delivery_source');
    }
    rec.deliveryStatuses.push({
      orderId:safeInt(order.id),fulfillmentSource:source,status:order.status
    });
    if(source==='owed_morning_prototype') rec.flags.push('test_only_order_not_delivery_proof');
    if(source==='paid_entitlement' && order.status==='delivered' &&
       rec.positiveSourceRows>0) rec.flags.push('credited_date_already_delivered');
    dates.set(day,rec);
  }

  for(const reservation of reservations) {
    const day=reservation.delivery_date;
    if(!validDay(day)) {globalFlags.push('reserved_date_invalid');continue;}
    const rec=dates.get(day)||initDate(day);
    if(reservation.status==='reserved') {
      rec.reservedPrototypeCount++;
      rec.flags.push('active_prototype_hold_on_date');
    }
    dates.set(day,rec);
  }

  for(const rec of dates.values()) {
    if(rec.positiveSourceRows>1)rec.flags.push('multiple_credit_sources_same_morning');
    if(rec.reversalSourceRows>rec.positiveSourceRows)rec.flags.push('reversal_exceeds_positive_sources');
    if(rec.signedClaimDays>1||rec.signedClaimDays<0)rec.flags.push('net_claim_outside_single_morning');
    if(rec.positiveSourceRows>0 &&
       rec.deliveryStatuses.some(x=>x.fulfillmentSource==='paid_entitlement' && x.status==='delivered')) {
      rec.flags.push('credited_date_already_delivered');
    }
    if(validDay(paidThroughDate) && rec.deliveryDate>paidThroughDate &&
       rec.positiveSourceRows>0) rec.flags.push('credit_claim_after_paid_through');
    if(rec.deliveryStatuses.length>1)rec.flags.push('multiple_delivery_orders_same_day');
    rec.flags=unique(rec.flags);
    rec.creditAdjustmentIds=unique(rec.creditAdjustmentIds);
    rec.sourceKinds=unique(rec.sourceKinds);
  }

  const adjustmentCoverage=[...adjustmentMap.values()].sort((a,b)=>a.id-b.id);
  for(const a of adjustmentCoverage) {
    a.provenanceMatchesAdjustment=(a.expectedDays===a.provenanceDays &&
      a.expectedPaise===a.provenancePaise);
    if(!a.provenanceMatchesAdjustment)globalFlags.push('legacy_or_incomplete_date_provenance');
    if(a.type==='credit' && a.provenanceMatchesAdjustment && a.provenanceRows===0 &&
       (a.expectedDays!==0||a.expectedPaise!==0)) {
      globalFlags.push('credit_adjustment_missing_source_dates');
    }
  }

  const owedInventory=[];
  let unassignedOwed=0,activeHeld=0;
  for(const ob of obligations) {
    const owed=safeInt(ob.owed_mornings);
    const fulfilled=safeInt(ob.fulfilled_mornings);
    const refunded=safeInt(ob.refunded_mornings);
    const remaining=owed-fulfilled-refunded;
    if(owed<=0||fulfilled<0||refunded<0||remaining<0) {
      globalFlags.push('invalid_obligation_balance');
    }
    unassignedOwed=sumChecked(unassignedOwed,Math.max(0,remaining));
    if(!ob.payment_id || ob.payment_id!==subscription.notes?.lastPaymentId) {
      globalFlags.push('obligation_payment_requires_review');
    }
    owedInventory.push({
      obligationId:safeInt(ob.id),status:ob.status,
      owedMornings:owed,fulfilledMornings:fulfilled,refundedMornings:refunded,
      remainingMornings:Math.max(0,remaining),
      targetMorningsAssigned:false
    });
  }
  for(const r of reservations) if(r.status==='reserved')activeHeld++;
  if(activeHeld>unassignedOwed)globalFlags.push('active_reservations_exceed_obligation_balance');
  if(obligations.length>0)globalFlags.push('owed_mornings_not_allocated_to_unique_compensation_dates');
  if(refundRequests.some(x=>['pending','processing','approved','processed'].includes(x.status))) {
    globalFlags.push('refund_requests_require_external_verification');
  }

  const gatewayReview=assessRecurringGatewaySnapshot({
    subscription,captureObservations,localRefundRequests:refundRequests,
    gatewaySnapshot
  });
  if(gatewayReview.reviewFlags.length)globalFlags.push('gateway_snapshot_discrepancies_present');
  const dateRows=[...dates.values()].sort((a,b)=>a.deliveryDate.localeCompare(b.deliveryDate));
  return {
    subscriptionId:Number(subscription.id),
    status:'finance_review_required',
    auditType:'internal_read_only_date_evidence',
    paidThroughDate:validDay(paidThroughDate)?paidThroughDate:null,
    nominalDailyRatePaise:dailyRate,
    dateRows,
    adjustmentCoverage,
    obligationInventory:{
      obligations:owedInventory,
      remainingUnassignedMornings:unassignedOwed,
      activePrototypeHolds:activeHeld
    },
    localRefundRequestCount:refundRequests.length,
    signedCaptureObservationCount:captureObservations.length,
    gatewayReview,
    reviewFlags:unique(globalFlags),
    manualDecisionRequired:true,
    // Never net date claims into owed mornings or compute a refund.
    ...noActions()
  };
}

/** Snapshot-only entrypoint. No HTTP route, no scheduled job, no write. */
export async function previewRecurringFinanceDecisionWorksheet(pool,{
  subscriptionId,gatewaySnapshot=null
}={}) {
  const id=Number(subscriptionId);
  if(!Number.isSafeInteger(id)||id<=0)return {success:false,reason:'invalid_subscription_id'};
  const {client,release}=await acquireClient(pool);
  try {
    await client.query('BEGIN TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY');
    const subResult=await client.query('SELECT * FROM customer_subscriptions WHERE id=$1',[id]);
    if(!subResult.rows.length){
      await client.query('COMMIT');
      return {success:false,reason:'subscription_not_found'};
    }
    const sub=subResult.rows[0];
    const paidThroughDate=await getEffectivePaidThroughDate(client,sub);
    const adj=await client.query(
      'SELECT id,adjustment_type,days_count,amount_paise FROM subscription_billing_adjustments WHERE subscription_id=$1 ORDER BY id',
      [id]);
    const sources=await client.query(
      'SELECT billing_adjustment_id,source_kind,source_reference,delivery_date::text AS delivery_date,days_delta,amount_paise,evidence_state,payment_id,billing_cycle_reference '+
      'FROM subscription_billing_credit_provenance WHERE subscription_id=$1 ORDER BY delivery_date,id',
      [id]);
    const orders=await client.query(
      'SELECT id,delivery_date::text AS delivery_date,fulfillment_source,status FROM subscription_delivery_orders WHERE subscription_id=$1 ORDER BY delivery_date,id',
      [id]);
    const obligations=await client.query(
      'SELECT id,status,payment_id,owed_mornings,fulfilled_mornings,refunded_mornings FROM subscription_recurring_morning_obligations WHERE subscription_id=$1 ORDER BY id',
      [id]);
    const reservations=await client.query(
      'SELECT delivery_date::text AS delivery_date,status FROM subscription_recurring_morning_reservations WHERE subscription_id=$1 ORDER BY delivery_date,id',
      [id]);
    const refunds=await client.query(
      'SELECT status,payment_id,approved_amount_paise,gateway_refund_id FROM refund_requests WHERE subscription_id=$1 ORDER BY id',
      [id]);
    const captures=await client.query(
      'SELECT gateway_payment_id,gateway_subscription_id,amount_paise,paid_count_at_event,proof_level FROM recurring_subscription_capture_observations WHERE subscription_id=$1 ORDER BY id',
      [id]);
    const review=buildRecurringFinanceDecisionWorksheet({
      subscription:sub,paidThroughDate,
      adjustments:adj.rows,creditSources:sources.rows,deliveryOrders:orders.rows,
      obligations:obligations.rows,reservations:reservations.rows,
      refundRequests:refunds.rows,captureObservations:captures.rows,gatewaySnapshot
    });
    await client.query('COMMIT');
    return {success:true,...review};
  } catch(err) {
    await client.query('ROLLBACK').catch(()=>{});
    throw err;
  } finally{release();}
}
