import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {
  assessRecurringGatewaySnapshot,previewRecurringGatewaySnapshotReconciliation
} from '../src/services/recurringGatewaySnapshotReconciliation.js';

const subscription={
  id:70,customer_id:11,plan_type:'month',total_amount_paise:1200000,
  razorpay_subscription_id:'sub_gateway_test_001',
  notes:{keyMode:'live',paidCount:2,months:6}
};
const payments=[
  {id:'pay_gateway_a',subscription_id:subscription.razorpay_subscription_id,
   invoice_id:'inv_gateway_01',status:'captured',captured:true,currency:'INR',
   amount:25000,amount_refunded:5000},
  {id:'pay_gateway_b',subscription_id:subscription.razorpay_subscription_id,
   invoice_id:'inv_gateway_02',status:'captured',captured:true,currency:'INR',
   amount:35000,amount_refunded:0}
];
const invoices=[
  {id:'inv_gateway_01',status:'paid',subscription_id:subscription.razorpay_subscription_id,
   payment_id:'pay_gateway_a',billing_start:1793491200,billing_end:1796083200},
  {id:'inv_gateway_02',status:'paid',subscription_id:subscription.razorpay_subscription_id,
   payment_id:'pay_gateway_b',billing_start:1796083200,billing_end:1798761600}
];
const refunds=[
  {id:'rfnd_gateway_01',payment_id:'pay_gateway_a',currency:'INR',
   status:'processed',amount:5000}
];
const observations=payments.map((p,i)=>({
  gateway_payment_id:p.id,gateway_subscription_id:subscription.razorpay_subscription_id,
  amount_paise:p.amount,paid_count_at_event:i+1,
  proof_level:'signed_webhook_payment_entity'
}));
const localRefundRequests=[{
  status:'processed',payment_id:'pay_gateway_a',gateway_refund_id:'rfnd_gateway_01',
  approved_amount_paise:5000
}];
const snapshot={
  subscriptionId:subscription.razorpay_subscription_id,
  accountMode:'live',retrievedAt:'2026-11-09T10:00:00Z',complete:true,
  payments,invoices,refunds
};
const run=(changes={})=>assessRecurringGatewaySnapshot({
  subscription,captureObservations:observations,
  localRefundRequests,gatewaySnapshot:snapshot,...changes
});
test('separately supplied 2-cycle Razorpay evidence matches exact captured payments and one processed refund',()=>{
  const result=run();
  assert.deepEqual(result.reviewFlags,[]);
  assert.equal(result.snapshotComplete,true);
  assert.equal(result.capturedPaymentCount,2);
  assert.equal(result.observedCapturedAmountPaise,60000);
  assert.equal(result.processedRefundAmountPaise,5000);
  assert.equal(result.outstandingGatewayRefundAmountPaise,0);
  assert.equal(result.gatewayCycles.length,2);
  assert.deepEqual(result.gatewayCycles.map(c=>c.capturedAmountPaise),[25000,35000]);
  assert.equal(result.paymentComparisons[0].observedWebhook,true);
  assert.equal(result.paymentComparisons[0].reportedRefundedPaise,5000);
  assert.equal(result.independentlyConfirmedSettlement,false);
  assert.equal(result.customerRefundableAmountPaise,null);
  assert.equal(result.customerPayableCreditPaise,null);
  assert.equal(result.mayAutoRefund,false);
  assert.equal(result.mayAutoApplyCredits,false);
  assert.equal(result.mayAutoGenerateDeliveries,false);
  assert.notEqual(result.observedCapturedAmountPaise,subscription.total_amount_paise,
    'Do not silently treat the six-month contract amount as collected cash');
});
test('missing gateway snapshot or missing invoice/cycle remains unresolved',()=>{
  const missing=run({gatewaySnapshot:null});
  assert.ok(missing.reviewFlags.includes('independent_gateway_snapshot_missing'));
  assert.equal(missing.observedCapturedAmountPaise,0);
  const noInvoice=run({gatewaySnapshot:{...snapshot,invoices:[],complete:false}});
  assert.ok(noInvoice.reviewFlags.includes('gateway_payment_cycle_invoice_missing'));
  assert.ok(noInvoice.reviewFlags.includes('gateway_snapshot_partial_or_unknown'));
  assert.equal(noInvoice.customerRefundableAmountPaise,null);
});
test('refunded statuses, partial refund and a missing processed receipt cannot be conflated',()=>{
  const changed=run({
    gatewaySnapshot:{...snapshot,
      payments:[{...payments[0],status:'refunded',amount_refunded:9000},payments[1]],
      refunds:[
        ...refunds,
        {id:'rfnd_gateway_pending',payment_id:'pay_gateway_a',
         status:'pending',currency:'INR',amount:4000}
      ]
    },
    localRefundRequests:[
      ...localRefundRequests,
      {status:'approved',gateway_refund_id:null,payment_id:'pay_gateway_b',approved_amount_paise:12000}
    ]
  });
  assert.equal(changed.capturedPaymentCount,2);
  assert.equal(changed.processedRefundAmountPaise,5000);
  assert.equal(changed.outstandingGatewayRefundAmountPaise,4000);
  for(const flag of ['gateway_refund_not_final','refund_totals_do_not_match_gateway_payment',
    'local_approved_refund_not_proof_of_gateway_settlement']){
    assert.ok(changed.reviewFlags.includes(flag),flag);
  }
});
test('forged payment identity, wrong currency, inconsistent amount and duplicate refund are flagged',()=>{
  const altered=run({
    gatewaySnapshot:{...snapshot,
      payments:[
        {...payments[0],amount:33000,currency:'USD',
          subscription_id:'sub_foreign',captured:false},
        payments[1]
      ],
      refunds:[...refunds,refunds[0]]
    }
  });
  for(const flag of ['gateway_payment_not_confirmed_captured_inr',
    'gateway_payment_foreign_subscription','gateway_and_webhook_observation_mismatch',
    'gateway_duplicate_or_invalid_refund_id']){
    assert.ok(altered.reviewFlags.includes(flag),flag);
  }
});
test('same invoice cycle with multiple payments or overlapping cycles is held for review',()=>{
  const altered=run({
    gatewaySnapshot:{...snapshot,
      invoices:[invoices[0],{...invoices[1],billing_start:1795000000}],
      payments:[payments[0],{...payments[1],invoice_id:'inv_gateway_01'}]
    }
  });
  assert.ok(altered.reviewFlags.includes('invoice_payment_conflict'));
  assert.ok(altered.reviewFlags.includes('multiple_payments_per_gateway_invoice_cycle'));
  const overlap=run({
    gatewaySnapshot:{...snapshot,
      invoices:[invoices[0],{...invoices[1],billing_start:1795000000}]
    }
  });
  assert.ok(overlap.reviewFlags.includes('overlapping_gateway_invoice_cycles'));
  assert.equal(altered.mayAutoRefund,false);
});
test('foreign processed refund cannot increase matched refund amount',()=>{
  const report=run({
    gatewaySnapshot:{...snapshot,refunds:[
      ...refunds,{id:'rfnd_foreign_gateway',payment_id:'pay_outside_subscription',
        currency:'USD',status:'processed',amount:500000}
    ]}
  });
  assert.equal(report.processedRefundAmountPaise,5000);
  assert.ok(report.reviewFlags.includes('processed_refund_not_linked_to_valid_gateway_payment'));
  assert.ok(report.reviewFlags.includes('gateway_refund_currency_or_payment_mismatch'));
  assert.equal(report.mayAutoRefund,false);
});

test('processed local claim with missing approved amount is reviewable, not payable',()=>{
  const report=run({localRefundRequests:[
    {...localRefundRequests[0],approved_amount_paise:null}
  ]});
  assert.ok(report.reviewFlags.includes('local_processed_refund_approved_amount_missing'));
  assert.equal(report.customerRefundableAmountPaise,null);
});

test('processed local refund must match exact gateway refund ID, payment ID and amount',()=>{
  const altered=run({localRefundRequests:[
    {status:'processed',gateway_refund_id:'rfnd_missing',
      payment_id:'pay_gateway_a',approved_amount_paise:5000},
    {status:'processed',gateway_refund_id:'rfnd_gateway_01',
      payment_id:'pay_gateway_b',approved_amount_paise:3000}
  ]});
  assert.ok(altered.reviewFlags.includes('local_processed_refund_missing_from_gateway_snapshot'));
  assert.ok(altered.reviewFlags.includes('local_processed_refund_receipt_mismatch'));
  assert.equal(altered.customerRefundableAmountPaise,null);
});
test('captures with foreign subscription or missing invoice never enter reconciled captured total',()=>{
  const altered=run({
    gatewaySnapshot:{...snapshot,
      payments:[
        {...payments[0],subscription_id:'sub_unrelated'},
        {...payments[1],invoice_id:'inv_missing'}
      ]
    }
  });
  assert.equal(altered.capturedPaymentCount,0);
  assert.equal(altered.observedCapturedAmountPaise,0);
  assert.ok(altered.reviewFlags.includes('capture_not_reconciled_to_subscription_cycle'));
  assert.equal(altered.mayAutoRefund,false);
});

test('two processed local requests for one refund must not be counted as two legitimate settlements',()=>{
  const duplicated=run({
    localRefundRequests:[...localRefundRequests,{...localRefundRequests[0]}]
  });
  assert.ok(duplicated.reviewFlags.includes('duplicate_local_processed_refund_claim'));
  assert.equal(duplicated.processedRefundAmountPaise,5000);
  assert.equal(duplicated.customerRefundableAmountPaise,null);
});

test('unobserved gateway payments, missing paid cycles and foreign data fail closed',()=>{
  const altered=run({
    captureObservations:[observations[0]],
    gatewaySnapshot:{...snapshot,accountMode:'test',
      subscriptionId:'sub_unrelated',retrievedAt:'not-a-time'}
  });
  for(const flag of ['gateway_snapshot_not_explicitly_live',
    'gateway_snapshot_foreign_subscription',
    'gateway_snapshot_retrieval_time_unverified',
    'gateway_payment_absent_from_signed_webhook_observations']){
    assert.ok(altered.reviewFlags.includes(flag),flag);
  }
});
test('complete multi-cycle gateway invoice evidence must cover paid cycles and paid invoices',()=>{
  const missingCycle=run({
    gatewaySnapshot:{...snapshot,
      invoices:[invoices[0]],
      payments:[payments[0]],
      refunds
    }
  });
  assert.ok(missingCycle.reviewFlags.includes('local_paid_cycles_exceed_gateway_invoice_evidence'));
  assert.ok(missingCycle.reviewFlags.includes('webhook_cycle_exceeds_gateway_invoice_evidence'));
  assert.ok(missingCycle.reviewFlags.includes('webhook_capture_absent_from_gateway_snapshot'));

  const unpaidInvoice=run({
    gatewaySnapshot:{...snapshot,
      invoices:[...invoices,{
        id:'inv_gateway_paid_unlinked',status:'paid',
        subscription_id:subscription.razorpay_subscription_id,
        payment_id:'pay_gateway_unseen',
        billing_start:1798761600,billing_end:1801440000
      }]
    }
  });
  assert.ok(unpaidInvoice.reviewFlags.includes('paid_gateway_invoice_without_matching_capture'));

  const testModeLocal=run({subscription:{
    ...subscription,notes:{...subscription.notes,keyMode:'test'}
  }});
  assert.ok(testModeLocal.reviewFlags.includes('local_gateway_mode_not_verified_live'));
  assert.equal(testModeLocal.mayAutoRefund,false);
});

test('non-integral currency subunits fail instead of rounded finance results',()=>{
  assert.throws(()=>run({
    gatewaySnapshot:{...snapshot,payments:[{...payments[0],amount:100.5},payments[1]]}
  }),/invalid_gateway_snapshot_payment_amount/);
  assert.throws(()=>run({
    gatewaySnapshot:{...snapshot,refunds:[{...refunds[0],amount:'5000.3'}]}
  }),/invalid_gateway_snapshot_refund_amount/);
});
test('invalid subscription IDs do not connect or read DB; reconciliation source contains no writes or Razorpay calls',async()=>{
  const pool={connect:async()=>{throw Error('Must not connect')}};
  assert.deepEqual(
    await previewRecurringGatewaySnapshotReconciliation(pool,{subscriptionId:'wrong',gatewaySnapshot:snapshot}),
    {success:false,reason:'invalid_subscription_id'}
  );
  const source=fs.readFileSync(new URL('../src/services/recurringGatewaySnapshotReconciliation.js',import.meta.url),'utf8');
  assert.match(source,/REPEATABLE READ READ ONLY/);
  assert.doesNotMatch(source,/INSERT INTO|UPDATE customer_|DELETE FROM|\.payments\.refund|\.payments\.fetch/);
  assert.doesNotMatch(fs.readFileSync(new URL('../src/server.js',import.meta.url),'utf8'),
    /previewRecurringGatewaySnapshotReconciliation/);
});
