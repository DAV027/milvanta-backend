import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {
  buildRecurringFinanceDecisionWorksheet,previewRecurringFinanceDecisionWorksheet
} from '../src/services/recurringFinanceDecisionWorksheet.js';

const sub={
  id:17,customer_id:19,razorpay_subscription_id:'sub_finance_worksheet_1',
  cost_per_day_paise:10500,total_amount_paise:1260000,plan_type:'month',
  notes:{keyMode:'live',fulfillmentEntitled:true,months:1,paidCount:1,
    lastPaymentId:'pay_finance_worksheet_1',paidThroughDate:'2026-12-05'}
};
const adjustments=[
  {id:1,adjustment_type:'credit',days_count:1,amount_paise:10500},
  {id:2,adjustment_type:'credit',days_count:2,amount_paise:21000},
  {id:3,adjustment_type:'credit',days_count:-1,amount_paise:-10500}
];
const sources=[
  {billing_adjustment_id:1,source_kind:'skip',delivery_date:'2026-11-12',
    days_delta:1,amount_paise:10500,evidence_state:'date_known_payment_unverified'},
  {billing_adjustment_id:2,source_kind:'vacation',delivery_date:'2026-11-12',
    days_delta:1,amount_paise:10500,evidence_state:'date_known_payment_unverified'},
  {billing_adjustment_id:2,source_kind:'vacation',delivery_date:'2026-11-13',
    days_delta:1,amount_paise:10500,evidence_state:'date_known_payment_unverified'},
  {billing_adjustment_id:3,source_kind:'unskip',delivery_date:'2026-11-12',
    days_delta:-1,amount_paise:-10500,evidence_state:'date_known_payment_unverified'}
];
const obligations=[{
  id:4,status:'approved',payment_id:'pay_finance_worksheet_1',
  owed_mornings:2,fulfilled_mornings:0,refunded_mornings:0
}];
const base={subscription:sub,paidThroughDate:'2026-12-05'};
const run=(rest={})=>buildRecurringFinanceDecisionWorksheet({...base,...rest});

test('multiple positive credit claims on one date remain flagged after an unskip reversal',()=>{
  const report=run({adjustments,creditSources:sources,
    obligations,refundRequests:[{status:'pending',payment_id:'pay_finance_worksheet_1'}]
  });
  const day=report.dateRows.find(x=>x.deliveryDate==='2026-11-12');
  assert.equal(day.positiveSourceRows,2);
  assert.equal(day.reversalSourceRows,1);
  assert.equal(day.signedClaimDays,1);
  assert.equal(day.signedClaimPaise,10500);
  assert.ok(day.flags.includes('multiple_credit_sources_same_morning'));
  assert.ok(day.flags.includes('date_credit_payment_cycle_unverified'));
  assert.equal(report.adjustmentCoverage.every(x=>x.provenanceMatchesAdjustment),true);
  assert.equal(report.obligationInventory.remainingUnassignedMornings,2);
  assert.ok(report.reviewFlags.includes('owed_mornings_not_allocated_to_unique_compensation_dates'));
  assert.ok(report.reviewFlags.includes('refund_requests_require_external_verification'));
  assert.equal(report.customerPayableCreditPaise,null);
  assert.equal(report.customerRefundableAmountPaise,null);
  assert.equal(report.newDeliveryEntitlementDays,null);
  assert.equal(report.mayAutoApplyCredits,false);
  assert.equal(report.mayAutoRefund,false);
  assert.equal(report.mayAutoGenerateDeliveries,false);
});

test('delivered physical order on already-credited day is an explicit conflict',()=>{
  const report=run({adjustments,creditSources:sources,
    deliveryOrders:[{id:55,delivery_date:'2026-11-12',
      fulfillment_source:'paid_entitlement',status:'delivered'}]
  });
  const day=report.dateRows[0];
  assert.ok(day.flags.includes('credited_date_already_delivered'));
  assert.equal(day.deliveryStatuses[0].status,'delivered');
  assert.equal(report.mayAutoGenerateDeliveries,false);
});

test('active prototype held morning does not become physical entitlement or proof',()=>{
  const report=run({reservations:[{
    delivery_date:'2026-12-06',status:'reserved'
  }],deliveryOrders:[{id:4,delivery_date:'2026-12-06',
    fulfillment_source:'owed_morning_prototype',status:'scheduled'}],
  obligations});
  const day=report.dateRows[0];
  assert.ok(day.flags.includes('active_prototype_hold_on_date'));
  assert.ok(day.flags.includes('test_only_order_not_delivery_proof'));
  assert.equal(report.obligationInventory.activePrototypeHolds,1);
  assert.equal(report.obligationInventory.remainingUnassignedMornings,2);
  assert.equal(report.newDeliveryEntitlementDays,null);
});

test('partial historical adjustments are listed individually and are not reconstructed from notes',()=>{
  const report=run({adjustments,creditSources:sources.slice(0,1)});
  assert.equal(report.adjustmentCoverage[0].provenanceMatchesAdjustment,true);
  assert.equal(report.adjustmentCoverage[1].provenanceMatchesAdjustment,false);
  assert.equal(report.adjustmentCoverage[2].provenanceMatchesAdjustment,false);
  assert.ok(report.reviewFlags.includes('legacy_or_incomplete_date_provenance'));
});

test('date arithmetic crosses months without coercing impossible dates',()=>{
  const report=run({adjustments:[{id:7,adjustment_type:'credit',days_count:1,amount_paise:10500}],
    creditSources:[{billing_adjustment_id:7,delivery_date:'2026-12-06',
      source_kind:'vacation',days_delta:1,amount_paise:10500,
      evidence_state:'date_known_payment_unverified'}]
  });
  assert.equal(report.dateRows[0].deliveryDate,'2026-12-06');
  assert.ok(report.dateRows[0].flags.includes('credit_claim_after_paid_through'));
  const impossible=run({adjustments:[{id:7,adjustment_type:'credit',days_count:1,amount_paise:10500}],
    creditSources:[{billing_adjustment_id:7,delivery_date:'2026-02-30',
      source_kind:'skip',days_delta:1,amount_paise:10500,
      evidence_state:'date_known_payment_unverified'}]
  });
  assert.ok(impossible.reviewFlags.includes('date_source_invalid_day'));
  assert.ok(impossible.reviewFlags.includes('legacy_or_incomplete_date_provenance'));
});

test('unskip without matching source and negative net date claim require finance review',()=>{
  const report=run({
    adjustments:[{id:9,adjustment_type:'credit',days_count:-1,amount_paise:-10500}],
    creditSources:[{billing_adjustment_id:9,delivery_date:'2026-11-12',source_kind:'unskip',
      days_delta:-1,amount_paise:-10500,evidence_state:'date_known_payment_unverified'}]
  });
  assert.ok(report.dateRows[0].flags.includes('reversal_exceeds_positive_sources'));
  assert.ok(report.dateRows[0].flags.includes('net_claim_outside_single_morning'));
});

test('invalid source rates, duplicate adjustment IDs, negative obligations and huge values fail closed',()=>{
  assert.throws(()=>run({adjustments:[...adjustments,adjustments[0]]}),
    /invalid_or_duplicate_finance_adjustment_id/);
  assert.throws(()=>run({subscription:{...sub,cost_per_day_paise:'nonsense'}}),
    /invalid_finance_review_integer/);
  assert.throws(()=>run({adjustments:[{id:1,adjustment_type:'credit',
    days_count:'123.5',amount_paise:100}]}),/invalid_finance_review_integer/);
  const bad=run({obligations:[{id:4,status:'approved',payment_id:'pay_finance_worksheet_1',
    owed_mornings:1,fulfilled_mornings:2,refunded_mornings:0}]});
  assert.ok(bad.reviewFlags.includes('invalid_obligation_balance'));
  assert.equal(bad.customerRefundableAmountPaise,null);
});

test('unknown gateway mode, 2+ installments and absent independent snapshot always block automatic payouts',()=>{
  const report=run({subscription:{...sub,notes:{...sub.notes,keyMode:'test',months:6,paidCount:2}}});
  assert.ok(report.reviewFlags.includes('gateway_mode_not_verified_live'));
  assert.ok(report.reviewFlags.includes('multimonth_policy_not_approved'));
  assert.ok(report.reviewFlags.includes('renewal_cycle_requires_review'));
  assert.ok(report.reviewFlags.includes('independent_gateway_snapshot_missing'));
  assert.equal(report.gatewayReview.status,'manual_reconciliation_required');
  assert.equal(report.independentlyConfirmedSettlement,false);
});

test('invalid subscription identifiers are rejected before opening a database connection',async()=>{
  const pool={connect:async()=>{throw Error('DB must not be touched')}};
  const result=await previewRecurringFinanceDecisionWorksheet(pool,{subscriptionId:'bad'});
  assert.deepEqual(result,{success:false,reason:'invalid_subscription_id'});
});

