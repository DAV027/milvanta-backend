import test from 'node:test';
import assert from 'node:assert/strict';
import {assessRecurringFinanceReconciliation, previewRecurringFinanceReconciliation}
  from '../src/services/recurringFinanceReconciliation.js';

const subscription={
  id:11,customer_id:25,plan_type:'month',
  razorpay_subscription_id:'sub_fixture_2026',cost_per_day_paise:10500,
  notes:{keyMode:'live',fulfillmentEntitled:true,paidCount:1,months:1,
    lastPaymentId:'pay_fixture_2026',paidThroughDate:'2026-12-05'}
};
const base={subscription,paidThroughDate:'2026-12-05'};

test('never invent a payable credit from overlapping billing adjustment and owed-morning ledgers',()=>{
  const result=assessRecurringFinanceReconciliation({
    ...base,
    billingAdjustments:[
      {adjustment_type:'credit',row_count:3,days_count:'2',amount_paise:'21000'}
    ],
    entitlementLedger:[{entry_type:'delivery_skipped',row_count:1,days_delta:'1',amount_paise:'10500'}],
    obligations:[{id:'40',status:'approved',owed_mornings:2,fulfilled_mornings:1,
      refunded_mornings:0,daily_rate_paise:10500,payment_id:'pay_fixture_2026',
      razorpay_subscription_id:'sub_fixture_2026'}],
    reservations:[{obligation_id:'40',status:'reserved',reservation_count:1}],
    refundRequests:[{status:'pending',requested_amount_paise:10500,approved_amount_paise:null}],
    deliveryOrders:[{fulfillment_source:'paid_entitlement',status:'delivered',order_count:1}]
  });
  assert.equal(result.isRecurring,true);
  assert.equal(result.billingAdjustments.credit.amountPaise,21000);
  assert.equal(result.owedMorningObligations.potentialUnsettledPaise,10500);
  assert.equal(result.owedMorningObligations.activeReservedMornings,1);
  assert.equal(result.owedMorningObligations.items[0].unreservedMornings,0);
  assert.equal(result.refundRequests.pendingPaise,10500);
  assert.ok(result.reviewFlags.includes('independent_credits_and_owed_mornings_overlap_unreconciled'));
  assert.ok(result.reviewFlags.includes('refund_and_owed_obligation_overlap_unreconciled'));
  assert.ok(result.reviewFlags.includes('outstanding_owed_morning_reservations'));
  assert.ok(result.reviewFlags.includes('delivery_vs_entitlement_ledger_count_mismatch'));
  assert.equal(result.customerPayableCreditPaise,null);
  assert.equal(result.customerRefundableAmountPaise,null);
  assert.equal(result.mayAutoRefund,false);
  assert.equal(result.mayAutoApplyCredits,false);
  assert.equal(result.mayAutoGenerateDeliveries,false);
});

test('missing physical-delivery ledger is a review error, including when zero ledger entries exist',()=>{
  const result=assessRecurringFinanceReconciliation({
    ...base,
    deliveryOrders:[{fulfillment_source:'paid_entitlement',status:'delivered',order_count:2}]
  });
  assert.ok(result.reviewFlags.includes('delivery_vs_entitlement_ledger_count_mismatch'));
  assert.equal(result.customerRefundableAmountPaise,null);
});

test('mismatched obligation payment ID and missing approved refund amount must be reviewed',()=>{
  const result=assessRecurringFinanceReconciliation({
    ...base,
    obligations:[{id:'42',status:'approved',owed_mornings:2,fulfilled_mornings:0,
      refunded_mornings:0,daily_rate_paise:10500,payment_id:'pay_wrong_payment',
      razorpay_subscription_id:subscription.razorpay_subscription_id}],
    refundRequests:[{status:'approved',requested_amount_paise:10000,
      approved_amount_paise:null,gateway_refund_id:null}]
  });
  assert.ok(result.reviewFlags.includes('obligation_and_payment_evidence_mismatch'));
  assert.ok(result.reviewFlags.includes('approved_refund_missing_amount'));
  assert.equal(result.mayAutoRefund,false);
});

test('net negative legacy billing adjustments and price inconsistencies are reported, not paid',()=>{
  const result=assessRecurringFinanceReconciliation({...base,billingAdjustments:[
    {adjustment_type:'credit',row_count:2,days_count:-1,amount_paise:-20000}
  ]});
  assert.ok(result.reviewFlags.includes('negative_net_credit_adjustment'));
  assert.ok(result.reviewFlags.includes('credit_amount_day_rate_mismatch'));
  assert.equal(result.requiresManualFinanceReview,true);
});

test('month 2+, captured payment unverified, processed refund without gateway receipt all hold release',()=>{
  const result=assessRecurringFinanceReconciliation({
    ...base,
    subscription:{...subscription,notes:{...subscription.notes,
      months:3,paidCount:2,keyMode:'test',fulfillmentEntitled:false}},
    refundRequests:[{status:'processed',requested_amount_paise:10500,
      approved_amount_paise:10500,gateway_refund_id:null}],
    deliveryOrders:[{fulfillment_source:'owed_morning_prototype',status:'delivered',order_count:1}]
  });
  for(const issue of ['multimonth_or_unknown_plan_policy','renewal_or_missing_cycle_reconciliation',
    'gateway_mode_not_live','captured_entitlement_not_verified',
    'processed_refund_missing_gateway_receipt','test_only_delivery_present_not_physical_proof']) {
    assert.ok(result.reviewFlags.includes(issue),issue);
  }
  assert.equal(result.refundRequests.processedPaise,10500);
});

test('clean single-cycle evidence still requires merchant review and does not grant a financial recommendation',()=>{
  const result=assessRecurringFinanceReconciliation({...base});
  assert.equal(result.reviewFlags.length,0);
  assert.equal(result.requiresManualFinanceReview,true);
  assert.equal(result.customerRefundableAmountPaise,null);
  assert.equal(result.owedMorningObligations.recordedCount,0);
});

test('invalid or overflowing financial inputs fail closed',()=>{
  assert.throws(()=>assessRecurringFinanceReconciliation({
    ...base,billingAdjustments:[{adjustment_type:'credit',days_count:1.5,amount_paise:500,row_count:1}]
  }),/invalid_finance_reconciliation_integer/);
  assert.throws(()=>assessRecurringFinanceReconciliation({
    ...base,obligations:[{id:1,owed_mornings:-1,fulfilled_mornings:0,
      refunded_mornings:0,daily_rate_paise:10500,status:'approved'}]
  }),/invalid_finance_reconciliation_nonnegative/);
  assert.throws(()=>assessRecurringFinanceReconciliation({
    ...base,billingAdjustments:[{adjustment_type:'mysterious',days_count:1,amount_paise:1,row_count:1}]
  }),/unrecognized_billing_adjustment_type/);
});

test('invalid subscription id aborts without opening a database connection',async()=>{
  const pool={connect:async()=>{throw Error('no DB may be touched')}};
  const result=await previewRecurringFinanceReconciliation(pool,{subscriptionId:'not-valid'});
  assert.equal(result.success,false);
  assert.equal(result.reason,'invalid_subscription_id');
});
